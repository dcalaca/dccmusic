function preserveOuterWhitespace(source: string, translated: string) {
  const leading = source.match(/^\s*/)?.[0] || ''
  const trailing = source.match(/\s*$/)?.[0] || ''
  return `${leading}${translated}${trailing}`
}

export function translateToAmericanEnglish(value: string) {
  if (!value) return value
  const trimmed = value.trim()
  if (!trimmed) return value

  let translated = exact[trimmed]
  if (translated === undefined) {
    translated = trimmed
    for (const [pattern, replacement] of phrases) {
      translated = typeof replacement === 'string'
        ? translated.replace(pattern, replacement)
        : translated.replace(pattern, replacement)
    }
  }

  return preserveOuterWhitespace(value, translated)
}
